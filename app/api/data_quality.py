"""Data-quality report endpoint.

Include ``router`` in the main FastAPI application. The endpoint serves the
latest report generated by ``python dq_check.py``. If no report exists yet,
it creates one from the raw CSVs (still without using the ingestion pipeline).
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from fastapi import APIRouter, HTTPException

from app.quality import run_quality_checks


PROJECT_ROOT = Path(__file__).resolve().parents[2]
RAW_DATA_DIR = PROJECT_ROOT / "data" / "raw"
REPORT_PATH = PROJECT_ROOT / "reports" / "data_quality_report.json"

router = APIRouter(tags=["data-quality"])


def load_or_create_report() -> dict[str, Any]:
    """Return the persisted DQ report, generating it if it does not exist."""
    if REPORT_PATH.is_file():
        try:
            return json.loads(REPORT_PATH.read_text(encoding="utf-8"))
        except (OSError, json.JSONDecodeError) as exc:
            raise RuntimeError(f"Unable to read DQ report at {REPORT_PATH}: {exc}") from exc

    try:
        report = run_quality_checks(RAW_DATA_DIR)
        REPORT_PATH.parent.mkdir(parents=True, exist_ok=True)
        REPORT_PATH.write_text(
            json.dumps(report, indent=2, ensure_ascii=False) + "\n",
            encoding="utf-8",
        )
        return report
    except (FileNotFoundError, OSError, ValueError) as exc:
        raise RuntimeError(f"Unable to generate DQ report: {exc}") from exc


@router.get("/data-quality/report")
def get_data_quality_report() -> dict[str, Any]:
    """Serve the same machine-readable report produced by the standalone CLI."""
    try:
        return load_or_create_report()
    except RuntimeError as exc:
        raise HTTPException(status_code=503, detail=str(exc)) from exc
